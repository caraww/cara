function toJalaali(gy, gm, gd) {
  const gdm = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334];
  let jy = gy <= 1600 ? 0 : 979;
  let y = gy - (gy <= 1600 ? 621 : 1600);
  const y2 = gm > 2 ? y + 1 : y;
  let days =
    365 * y + Math.floor((y2 + 3) / 4) - Math.floor((y2 + 99) / 100) +
    Math.floor((y2 + 399) / 400) - 80 + gd + gdm[gm - 1];
  jy += 33 * Math.floor(days / 12053);
  days %= 12053;
  jy += 4 * Math.floor(days / 1461);
  days %= 1461;
  if (days > 365) {
    jy += Math.floor((days - 1) / 365);
    days = (days - 1) % 365;
  }
  const jm = days < 186 ? 1 + Math.floor(days / 31) : 7 + Math.floor((days - 186) / 30);
  const jd = 1 + (days < 186 ? days % 31 : (days - 186) % 30);
  return [jy, jm, jd];
}

/** ISO date → «۳۰ آبان ۱۴۰۵» for the visible byline (schema keeps the ISO form). */
function faDate(iso) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(iso));
  if (!m) return String(iso);
  const [jy, jm, jd] = toJalaali(+m[1], +m[2], +m[3]);
  return `${faNum(jd)} ${FA_MONTHS[jm - 1]} ${faNum(jy)}`;
}

