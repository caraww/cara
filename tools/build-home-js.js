const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { minify_sync } = require("terser");

const root = path.resolve(__dirname, "..");
const SYNC = [
  "lib/works-pricing.js",
  "js/sale.js",
  "js/palette.js",
  "js/works.js",
  "js/beads.js",
  "js/home.js",
];
const DEFER = [
  "js/featured-work.js",
  "js/home-blog-feed.js",
  "js/nav-hero.js",
  "js/hero-stage.js",
  "js/weave.js",
  "js/decor.js",
  "js/contact.js",
  "js/pwa.js",
  "js/analytics.js",
  "js/recovery.js",
];
const SYNC_BUNDLE = "js/home-main.bundle.js";
const DEFER_BUNDLE = "js/home-defer.bundle.js";
const SYNC_BLOCK = /<!-- HOME-JS-SYNC:START([\s\S]*?)HOME-JS-SYNC:END -->/;
const DEFER_BLOCK = /<!-- HOME-JS-DEFER:START([\s\S]*?)HOME-JS-DEFER:END -->/;

function read(file) {
  return fs.readFileSync(path.join(root, file), "utf8");
}

function extractScripts(html, block, fallback) {
  const match = html.match(block);
  const text = match ? match[1] : fallback.map((file) => `<script src="/${file}"></script>`).join("\n");
  return [...text.matchAll(/<script[^>]+src="([^"]+)"/g)]
    .map((m) => m[1].split("?")[0].replace(/^\//, ""));
}

function buildBundle(files) {
  let out = "/* Generated by tools/build-home-js.js; do not edit directly. */\n";
  for (const file of files) {
    out += `\n/* ${file} */\n${read(file).trimEnd()}\n;`;
  }
  const result = minify_sync(out, {
    compress: { passes: 2 },
    mangle: true,
    format: { comments: false },
  });
  if (result.error) throw result.error;
  return `${result.code}\n`;
}

function replaceBundle(html, attr, file, version, defer) {
  const tag = `<script src="/${file}?v=${version}"${defer ? " defer" : ""} data-home-${attr}="1"></script>`;
  const re = new RegExp(`<script[^>]+data-home-${attr}[^>]*></script>`);
  if (re.test(html)) return html.replace(re, tag);
  const block = html.match(attr === "sync" ? SYNC_BLOCK : DEFER_BLOCK);
  if (!block) throw new Error(`homepage ${attr} script source block was not found`);
  const at = block.index + block[0].length;
  return html.slice(0, at) + "\n    " + tag + html.slice(at);
}

function build() {
  const html = read("index.html");
  const syncCss = buildBundle(extractScripts(html, SYNC_BLOCK, SYNC));
  const deferCss = buildBundle(extractScripts(html, DEFER_BLOCK, DEFER));
  const syncVersion = crypto.createHash("sha1").update(syncCss).digest("hex").slice(0, 10);
  const deferVersion = crypto.createHash("sha1").update(deferCss).digest("hex").slice(0, 10);
  let out = replaceBundle(html, "sync", SYNC_BUNDLE, syncVersion, true);
  out = replaceBundle(out, "defer", DEFER_BUNDLE, deferVersion, true);
  return { syncCss, deferCss, html: out, syncVersion, deferVersion };
}

if (require.main === module) {
  const { syncCss, deferCss, html } = build();
  fs.writeFileSync(path.join(root, SYNC_BUNDLE), syncCss);
  fs.writeFileSync(path.join(root, DEFER_BUNDLE), deferCss);
  fs.writeFileSync(path.join(root, "index.html"), html);
  console.log(`Wrote ${SYNC_BUNDLE} and ${DEFER_BUNDLE}`);
}

module.exports = { SYNC, DEFER, SYNC_BUNDLE, DEFER_BUNDLE, build, buildBundle, extractScripts };
