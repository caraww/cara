const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { transform } = require("lightningcss");

const root = path.resolve(__dirname, "..");
const SOURCES = [
  "css/fonts.css",
  "css/home.css",
  "css/weave.css",
  "css/decor.css",
  "css/home-blog-feed.css",
  "css/weaving.css",
  "css/page-frame.css",
  "css/accessibility.css",
  "css/fixes.css",
  "css/recovery.css",
  "css/polish.css",
  "css/nav-hero.css",
  "css/premium.css",
  "css/site-footer.css",
  "css/theme.css",
];
const BUNDLE = "css/home.bundle.css";
const BLOCK = /<!-- HOME-CSS-SOURCES:START([\s\S]*?)HOME-CSS-SOURCES:END -->/;

function read(file) {
  return fs.readFileSync(path.join(root, file), "utf8");
}

function extractSources(html) {
  const block = html.match(BLOCK);
  const text = block
    ? block[1]
    : SOURCES.map((file) => `<link rel="stylesheet" href="/${file}" />`).join("\n");
  return [...text.matchAll(/<link[^>]+rel="stylesheet"[^>]*href="([^"]+)"/g)]
    .map((match) => match[1].split("?")[0].replace(/^\//, ""));
}

function buildCss(sources = SOURCES) {
  const tokens = read("css/tokens.css");
  let out = "/* Generated by tools/build-home-css.js; do not edit directly. */\n";
  for (const file of sources) {
    let css = read(file);
    if (file === "css/polish.css") {
      css = css.replace('@import url("/css/tokens.css");', tokens);
    }
    out += `\n/* ${file} */\n${css.trimEnd()}\n`;
  }
  return transform({ filename: BUNDLE, code: Buffer.from(out), minify: true }).code.toString();
}

function buildHtml(html, version) {
  const link = `<link rel="stylesheet" href="/${BUNDLE}?v=${version}" data-home-bundle="1" />`;
  if (/<link[^>]+data-home-bundle[^>]*>/.test(html)) {
    return html.replace(/<link[^>]+data-home-bundle[^>]*>/, link);
  }
  const block = html.match(BLOCK);
  if (!block) throw new Error("homepage stylesheet source block was not found");
  const insertAt = block.index + block[0].length;
  return html.slice(0, insertAt) + "\n    " + link + html.slice(insertAt);
}

function build() {
  const html = read("index.html");
  const css = buildCss(extractSources(html));
  const version = crypto.createHash("sha1").update(css).digest("hex").slice(0, 10);
  return { css, html: buildHtml(html, version), version };
}

if (require.main === module) {
  const { css, html } = build();
  fs.writeFileSync(path.join(root, BUNDLE), css);
  fs.writeFileSync(path.join(root, "index.html"), html);
  console.log(`Wrote ${BUNDLE} (${(Buffer.byteLength(css) / 1024).toFixed(1)} KB)`);
}

module.exports = { SOURCES, BUNDLE, build, buildCss, buildHtml, extractSources };
